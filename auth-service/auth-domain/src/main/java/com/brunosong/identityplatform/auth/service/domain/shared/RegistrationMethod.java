package com.brunosong.identityplatform.auth.service.domain.shared;

/**
 * 셀프 가입이 어떤 자격증명을 만드는가. {@link Realm} 이 realm 마다 하나씩 들고 있다.
 *
 * <h2>왜 realm 이 방식까지 정하나</h2>
 * "가입할 수 있는가"({@link Realm#allowsSelfRegistration()})와 "무엇으로 가입하는가"는 붙어 있는
 * 결정이다. 포털 고객은 비밀번호 계정을 갖지만 <b>직원은 갖지 않는다</b> — 직원 계정을 만드는
 * 코드가 이메일 계정만 만들기 때문이다. 그래서 어드민 realm 에 비밀번호 가입을 열면 이 서비스가
 * 만들 수 없는 계정을 요구하는 경로가 생긴다.
 *
 * <p>둘을 한 자리에 두면 그런 조합이 애초에 표현되지 않는다. realm 하나가 "열려 있고, 이 방식으로"
 * 를 함께 말한다.
 *
 * <p>가입 경로도 이 값으로 갈린다. 자기 realm 의 방식이 아닌 경로는 <b>404</b> 다 — 403 이 아닌
 * 이유는 "여기에도 그 API 가 있긴 한데 막혀 있다" 를 알려줄 이유가 없기 때문이다.
 */
public enum RegistrationMethod {

    /**
     * 비밀번호를 정해 가입한다. 이메일이 곧 로그인 아이디다.
     *
     * <p>가입 즉시 계정이 쓸 수 있는 상태가 되지만, <b>이메일 소유는 확인되지 않는다</b> —
     * 남의 주소로도 가입할 수 있다.
     */
    PASSWORD,

    /**
     * 비밀번호 없이 이메일 인증번호로 가입한다.
     *
     * <p>정할 비밀번호가 없다. 대신 <b>인증번호를 받아낸 것이 곧 그 주소의 주인이라는 증거</b>라,
     * 가입 시점에 이메일 소유가 확인된다 — {@link #PASSWORD} 에는 없는 성질이다.
     */
    EMAIL_OTP,
}
