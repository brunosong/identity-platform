/**
 * <b>인가 흐름 채널</b> — 로그인하는 사람의 <b>브라우저</b>가 직접 들르는 자리.
 *
 * <h2>OIDC 가 정한 자리</h2>
 * 대부분은 브라우저가 들른다. 앱은 브라우저를 이리로 보내고 빠지며, 로그인이 끝날 때까지 아무것도
 * 보지 못한다. 돌려주는 것도 JSON 이 아니라 사람이 보는 화면이다. 앱이 직접 부르는 것은 둘뿐이다.
 * code 를 토큰으로 바꾸는 토큰 엔드포인트와, 토큰 주인이 누구인지 묻는 userinfo 다.
 *
 * <p>부르는 주체가 다르면 채널이 다르다는 규칙을 그대로 따른 것이다. {@code broker} 와 성격이
 * 같다 — 그쪽도 로그인 흐름 중에 브라우저가 들르는 자리다.
 *
 * <h2>여기의 규칙</h2>
 * <ul>
 *   <li><b>토큰이 없는 호출자뿐이다.</b> 로그인하러 오는 사람이라 당연하다. 대신 요청에 실려 온
 *       값을 하나도 믿지 않는다 — 앱 이름도 돌아갈 주소도 요청자가 적어 보낸 값이다.</li>
 *   <li><b>거절할 때 돌려보내지 않는다.</b> 등록되지 않은 앱이나 주소면 우리 화면에서 끝낸다.
 *       적혀 온 주소로 오류를 실어 보내는 것 자체가 배달이다.</li>
 *   <li><b>실패 사유를 나누지 않는다.</b> 모르는 앱인지 등록되지 않은 주소인지 알려주면
 *       그것으로 등록된 값을 찍어볼 수 있다.</li>
 *   <li><b>비밀번호는 여기서만 받는다.</b> 이 채널이 있는 이유가 그것이다. 앱의 코드에 비밀번호를
 *       다루는 자리가 없어야 한다.</li>
 * </ul>
 *
 * <h2>경로</h2>
 * <pre>
 * GET  /realms/{realm}/auth         인가 요청 입구. 로그인 화면을 그린다
 * </pre>
 *
 * Keycloak 은 {@code /realms/{realm}/protocol/openid-connect/auth} 다. {@code protocol/openid-connect}
 * 는 한 realm 이 여러 프로토콜(SAML 등)을 낼 때 필요한 칸이라 우리는 두지 않았다.
 */
