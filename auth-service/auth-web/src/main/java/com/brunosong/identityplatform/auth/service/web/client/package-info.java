/**
 * <b>client 채널</b> — 최종 사용자의 브라우저·앱이 직접 부르는 API.
 *
 * <h2>채널이 패키지의 첫 세그먼트인 이유</h2>
 * 서브도메인(identity/authorization)이 "이 코드가 누구 것인가" 를 말한다면, 채널은
 * <b>"누가 이것을 부르는가"</b> 를 말한다. 둘은 다른 축이고, MSA 로 가면 갈라지는 축이 채널이다 —
 * 게이트웨이 라우팅, 네트워크 구역, 레이트 리밋, 그리고 결국 배포 단위가 채널을 따라 나뉜다.
 * 서브도메인을 따라 나뉘지 않는다.
 *
 * <p>그래서 채널을 위에 두고 서브도메인을 아래에 둔다. 이 패키지를 통째로 들어내면 그것이 곧
 * "사용자용 auth" 서비스가 된다.
 *
 * <h2>여기의 규칙</h2>
 * <ul>
 *   <li><b>인증되지 않은 호출자가 있다.</b> 로그인·가입·인증번호 발송은 토큰 없이 들어온다.
 *       그러므로 계정 열거를 막는 응답 규칙(있든 없든 같은 응답)이 여기서 지켜져야 한다.</li>
 *   <li><b>남의 데이터를 다루지 않는다.</b> 조회 키는 언제나 토큰의 {@code sub} 다. 경로나 본문으로
 *       식별자를 받으면 남의 것을 적어 넣는 것으로 남의 데이터가 열린다.</li>
 *   <li><b>권한을 다루지 않는다.</b> 역할 부여·정책 편집은 {@code admin} 채널의 일이다.
 *       여기서 할 수 있는 것은 자기 권한을 <i>읽는</i> 것까지다.</li>
 *   <li><b>realm 은 경로가 정한다</b> — {@code /api/auth/realms/{realm}/...}.
 *       그 realm 의 키로만 검증되므로 realm 을 사칭할 수 없다.</li>
 * </ul>
 *
 * <p>새 엔드포인트가 위 중 하나라도 어기면 그것은 이 채널의 것이 아니다.
 *
 * <h2>경로에 접두어가 없다 — {@code /api/admin} 이 아니면 여기다</h2>
 * <pre>
 * /api/auth/realms/{realm}/**   로그인 · 가입 · 로그아웃 · 재발급 · 내 권한
 * </pre>
 *
 * 채널 접두어를 한쪽({@code admin})에만 둔다. 둘 다 두면 어느 쪽도 아닌 경로가 생길 수 있고,
 * 그런 경로는 게이트웨이 규칙 어디에도 걸리지 않는다. 한쪽만 두면 모든 경로가 반드시 둘 중
 * 하나로 갈린다.
 *
 * <p>대신 <b>잊으면 공개되는 쪽이 기본값</b>이 된다. 그래서 이 채널의 규칙(위 네 가지)이
 * 규율로만 서 있으면 안 되고, 실제 방어는 각 엔드포인트가 직접 한다 — 로그인이 필요한 것은
 * {@code caller.require} 로, 남의 데이터를 막는 것은 조회 키를 토큰에서만 읽는 것으로.
 */
